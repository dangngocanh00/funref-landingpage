  const storageKey = 'funagency-language';
  const getStoredLanguage = () => {
    try {
      return localStorage.getItem(storageKey) || 'en';
    } catch (error) {
      return 'en';
    }
  };

  const getTranslation = (language, key) => translations[language]?.[key] || translations.en[key] || key;

  const applyTranslations = (language) => {
    document.documentElement.lang = language;
    document.querySelectorAll('[data-i18n]').forEach((element) => {
      element.textContent = getTranslation(language, element.dataset.i18n);
    });
    document.querySelectorAll('[data-i18n-aria-label]').forEach((element) => {
      element.setAttribute('aria-label', getTranslation(language, element.dataset.i18nAriaLabel));
    });
    document.querySelectorAll('[data-language]').forEach((button) => {
      const isActive = button.dataset.language === language;
      button.classList.toggle('is-active', isActive);
      button.setAttribute('aria-pressed', String(isActive));
    });
    window.dispatchEvent(new CustomEvent('languagechange', { detail: { language } }));
  };

  const setLanguage = (language) => {
    const nextLanguage = translations[language] ? language : 'en';
    try {
      localStorage.setItem(storageKey, nextLanguage);
    } catch (error) {
      // The page remains usable when storage is unavailable.
    }
    applyTranslations(nextLanguage);
  };

  window.FunAgencyI18n = {
    getLanguage: getStoredLanguage,
    getTranslation,
    setLanguage,
    applyTranslations
  };

  document.addEventListener('DOMContentLoaded', () => {
    applyTranslations(getStoredLanguage());
    document.querySelectorAll('[data-language]').forEach((button) => {
      button.addEventListener('click', () => setLanguage(button.dataset.language));
    });
  });
